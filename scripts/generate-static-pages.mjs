import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = path.join(root, 'src/lib/payload/static-pages.generated.ts');

const {
  blocksFromImported,
  isPublishedImport,
  loadImportedDocuments,
} = await import('../src/payload/seed/import-markdown.ts');

const pages = loadImportedDocuments()
  .filter((doc) => isPublishedImport(doc.slug, doc.importStatus))
  .map((doc) => ({
    id: 0,
    slug: doc.slug,
    title: doc.title,
    sourceUrl: doc.sourceUrl,
    blocks: blocksFromImported(doc, new Map()),
    updatedAt: new Date(0).toISOString(),
    createdAt: new Date(0).toISOString(),
    _status: 'published',
  }));

const fileContents = `// Generated by scripts/generate-static-pages.mjs — do not edit
import type { Page } from '@/payload/payload-types';

const pages: Page[] = ${JSON.stringify(pages, null, 2)} as Page[];

export const staticPagesBySlug = new Map(pages.map((page) => [page.slug, page]));
`;

fs.writeFileSync(outputPath, fileContents);
console.log(`[generate:static-pages] Wrote ${pages.length} pages to ${path.relative(root, outputPath)}`);
