import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = path.join(root, 'src/lib/payload/static-pages.generated.ts');

const {
  blocksFromImported,
  buildStaticMediaByPath,
  isPublishedImport,
  loadImportedDocuments,
} = await import('../src/payload/seed/import-markdown.ts');

function syncAssetsToPublic(assetPaths) {
  const assetsRoot = path.join(root, 'public/assets');

  for (const assetPath of assetPaths) {
    const source = path.join(root, 'src/assets', assetPath);
    const destination = path.join(assetsRoot, assetPath);

    if (!fs.existsSync(source)) {
      console.warn(`[generate:static-pages] Missing asset: ${assetPath}`);
      continue;
    }

    fs.mkdirSync(path.dirname(destination), { recursive: true });
    fs.copyFileSync(source, destination);
  }
}

const documents = loadImportedDocuments().filter((doc) =>
  isPublishedImport(doc.slug, doc.importStatus),
);

const mediaByPath = buildStaticMediaByPath(documents);

syncAssetsToPublic(mediaByPath.keys());

const pages = documents.map((doc) => ({
  id: 0,
  slug: doc.slug,
  title: doc.title,
  sourceUrl: doc.sourceUrl,
  blocks: blocksFromImported(doc, mediaByPath),
  updatedAt: new Date(0).toISOString(),
  createdAt: new Date(0).toISOString(),
  _status: 'published',
}));

const fileContents = `// Generated by scripts/generate-static-pages.mjs — do not edit
import type { Page } from '@/payload/payload-types';

const pages: Page[] = ${JSON.stringify(pages, null, 2)} as Page[];

export const staticPagesBySlug = new Map(pages.map((page) => [page.slug, page]));
`;

fs.writeFileSync(outputPath, fileContents);
console.log(
  `[generate:static-pages] Synced ${mediaByPath.size} assets and wrote ${pages.length} pages to ${path.relative(root, outputPath)}`,
);
